// Generates the mobile app's bundled offline dataset from the canonical question
// bank, so the iOS app works with zero network from first launch. Emits a single
// generated module, mobile/src/data/offline-data.ts, containing:
//   • the roadmap structure (topics → level/checkpoint metadata), and
//   • every non-private question WITH its answer + explanation (the offline
//     learning mode grades on-device; the offline quiz selects + grades locally).
//
// The data is embedded as a JSON string parsed at runtime (not an object
// literal) so tsc doesn't have to infer a giant literal type. Re-run after any
// question/roadmap change:  node <bundled>.cjs   (see scripts/ validation).

import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { questions, PRIVATE_CATEGORIES } from '../lib/quiz-data';
import { computeImportance } from '../lib/importance';
import { roadmapStructure, ROADMAP_TOPICS, ROADMAP_TOPICS as TOPICS, levelQuestionIds, checkpointQuestionIds, topicLevelCount, topicCheckpointCount, QUESTIONS_PER_LEVEL } from '../lib/roadmap';

interface OfflineQuestion {
  id: string;
  tags: string[];
  introduction: string;
  question: string;
  options: string[];
  correctAnswer: number;
  explanation: string;
  category: string;
  difficulty: number;
  // Resolved importance (1–10) so the offline quiz can weight selection like the
  // server does (the hand-judged score, or the heuristic for un-scored items).
  importance: number;
}

const nonPrivate = questions.filter((q) => !PRIVATE_CATEGORIES.includes(q.category));
const byId = new Map(nonPrivate.map((q) => [q.id, q]));

const slim = (q: (typeof questions)[number]): OfflineQuestion => ({
  id: q.id,
  tags: q.tags,
  introduction: q.introduction,
  question: q.question,
  options: q.options,
  correctAnswer: q.correctAnswer,
  explanation: q.explanation,
  category: q.category,
  difficulty: q.difficulty,
  importance: computeImportance(q),
});

// Integrity: every roadmap level/checkpoint must resolve to its full question set
// from the bundled (non-private) pool, or offline lessons would have gaps.
let problems = 0;
for (const topic of TOPICS) {
  for (let lvl = 1; lvl <= topicLevelCount(topic); lvl++) {
    for (const id of levelQuestionIds(topic, lvl)) {
      if (!byId.has(id)) { problems++; console.error(`missing ${id} (${topic} L${lvl})`); }
    }
  }
  for (let cp = 1; cp <= topicCheckpointCount(topic); cp++) {
    if (checkpointQuestionIds(topic, cp).some((id) => !byId.has(id))) {
      problems++; console.error(`checkpoint ${topic} #${cp} has missing questions`);
    }
  }
}
if (problems > 0) {
  console.error(`\n❌ ${problems} integrity problem(s); aborting generation`);
  process.exit(1);
}

const payload = {
  generatedAt: new Date().toISOString(),
  questionsPerLevel: QUESTIONS_PER_LEVEL,
  structure: { topics: ROADMAP_TOPICS, structure: roadmapStructure() },
  questions: nonPrivate.map(slim),
};

const json = JSON.stringify(payload);
const out = `// AUTO-GENERATED by scripts/generate-mobile-offline.ts — DO NOT EDIT BY HAND.
// Bundled offline dataset (roadmap structure + all non-private questions with
// answers) so the app works fully offline from first launch. Regenerate after
// any question change. Embedded as a parsed JSON string to keep tsc fast.
/* eslint-disable */
const RAW = ${JSON.stringify(json)};
const DATA: unknown = JSON.parse(RAW);
export default DATA;
`;

// Resolve from the project root (cwd) so this works whether run from source or
// from an esbuild bundle in a temp dir.
const target = resolve(process.cwd(), 'mobile/src/data/offline-data.ts');
writeFileSync(target, out);

const kb = Math.round(json.length / 1024);
console.log(`✅ Wrote ${target}`);
console.log(`   ${payload.questions.length} questions, ${ROADMAP_TOPICS.length} roadmap topics, ~${kb} KB`);
