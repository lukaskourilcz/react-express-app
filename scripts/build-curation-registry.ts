// Regenerates lib/curation-registry.ts from the audit ledger.
//   npm run build:curation-registry
//
// The ledger (docs/audit/devshark-content-ledger.json) is the record: every
// score, every piece of evidence, every rationale. The registry is the compact
// projection the server loads on every request — id, the hash of the exact
// content the decision was made about, the scores and the decision. Keeping
// the two apart means a request never parses megabytes of rationale, and the
// launch contract's freshness check means the registry can never quietly
// disagree with the ledger it claims to summarise.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  isLedgerDecision,
  registryEntryConsistent,
  type RegistryEntry,
} from '../shared/curation';

export const LEDGER_PATH = path.join('docs', 'audit', 'devshark-content-ledger.json');
export const REGISTRY_PATH = path.join('lib', 'curation-registry.ts');

export interface LedgerFile {
  schema: string;
  auditedOn: string;
  items: LedgerItem[];
}

/** The ledger row shape the registry is built from. Rationale, evidence and
 * defects are carried in the ledger only. */
export interface LedgerItem {
  id: string;
  kind: 'question' | 'coding-task';
  contentHash: string;
  cs: { hash: string | null; status: string } | null;
  revision: number;
  quality: RegistryEntry['dimensions'];
  qualityScore: number;
  relevance: RegistryEntry['markers'];
  relevanceScore: number;
  decision: string;
  retireReason: string | null;
  reviewedAt: string;
  [extra: string]: unknown;
}

export function readLedger(root = process.cwd()): LedgerFile {
  return JSON.parse(readFileSync(path.join(root, LEDGER_PATH), 'utf8')) as LedgerFile;
}

export function registryFromLedger(ledger: LedgerFile): RegistryEntry[] {
  const seen = new Set<string>();
  const out: RegistryEntry[] = [];
  for (const item of ledger.items) {
    if (seen.has(item.id)) throw new Error(`ledger has two rows for ${item.id}`);
    seen.add(item.id);
    if (!isLedgerDecision(item.decision)) throw new Error(`${item.id}: unknown decision ${item.decision}`);
    const entry: RegistryEntry = {
      id: item.id,
      kind: item.kind,
      hash: item.contentHash,
      cs: item.cs?.hash ?? null,
      relevance: item.relevanceScore,
      quality: item.qualityScore,
      markers: item.relevance,
      dimensions: item.quality,
      decision: item.decision,
      ...(item.retireReason ? { reason: item.retireReason } : {}),
      reviewedAt: item.reviewedAt,
      revision: item.revision,
    };
    if (!registryEntryConsistent(entry)) throw new Error(`${item.id}: scores do not add up to their totals`);
    out.push(entry);
  }
  return out.sort((a, b) => a.id.localeCompare(b.id));
}

export function renderCurationRegistry(entries: readonly RegistryEntry[], auditedOn: string): string {
  const rows = entries.map((entry) => `  ${JSON.stringify(entry)},`).join('\n');
  return `// Generated by scripts/build-curation-registry.ts from ${LEDGER_PATH}. Do not edit by hand.\n// One row per reviewed item: the hash of the exact content the decision was made about, the\n// scores, and the decision. Rationale and evidence stay in the ledger.\n\nimport type { RegistryEntry } from '../shared/curation';\n\nexport const REGISTRY_AUDITED_ON = ${JSON.stringify(auditedOn)};\n\nexport const REVIEW_REGISTRY: readonly RegistryEntry[] = [\n${rows}\n];\n`;
}

const isMain = (process.argv[1] && /build-curation-registry/.test(process.argv[1] ?? '')) || process.env.CURATION_REGISTRY_WRITE === '1';
if (isMain) {
  const ledger = readLedger();
  const entries = registryFromLedger(ledger);
  const target = path.join(process.cwd(), REGISTRY_PATH);
  writeFileSync(target, renderCurationRegistry(entries, ledger.auditedOn));
  console.log(`wrote ${target} (${entries.length} entries)`);
}
