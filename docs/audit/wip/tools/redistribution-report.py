# Lists the retired-section items whose review proposes moving them into a live
# bank. They are never applied automatically: the applier skips them, because
# moving an item into a live level is a content decision, not a rewrite.
#
# Usage: python3 redistribution-report.py <reviewDir> <inventoryDir> > out.md
import json, os, re, sys

REVIEW, INV = sys.argv[1], sys.argv[2]

TOPICS = ('general', 'nodejs', 'node', 'devops', 'databases', 'security', 'react',
          'javascript', 'typescript', 'system-design', 'nextjs', 'git', 'html',
          'css', 'algorithms', 'dsa', 'ai')
# Reviewers name a destination as "general level 16", "general L7" or
# "javascript L17 (Type Coercion)"; accept all three spellings.
DEST = re.compile(r'\b(' + '|'.join(TOPICS) + r')\b[^.]{0,40}?\b(?:level\s*|L)(\d+)', re.I)


def destination(rationale):
    m = DEST.search(rationale or '')
    if not m:
        return '—'
    topic = m.group(1).lower()
    return f'{"nodejs" if topic == "node" else topic} level {m.group(2)}'


inventory = {}
for name in sorted(os.listdir(INV)):
    if name.startswith('batch-'):
        for item in json.load(open(os.path.join(INV, name), encoding='utf-8')):
            inventory[item['id']] = item

rows = []
for name in sorted(os.listdir(REVIEW)):
    if not name.endswith('.jsonl'):
        continue
    for line in open(os.path.join(REVIEW, name), encoding='utf-8'):
        if not line.strip():
            continue
        r = json.loads(line)
        item = inventory.get(r['id'])
        if not item or item.get('delivery') != 'retired-section' or r['decision'] != 'rewrite':
            continue
        rows.append((item.get('category', '?'), r['id'], destination(r.get('rationale')),
                     r.get('objective', '').strip(), (r.get('rationale') or '').strip()))

def sort_key(row):
    m = re.match(r'(.*) level (\d+)$', row[2])
    return (m.group(1), int(m.group(2)), row[1]) if m else ('~', 0, row[1])


rows.sort(key=sort_key)

print('# devShark redistribution candidates\n')
print('Generated by `docs/audit/wip/tools/redistribution-report.py`. These are')
print('items in a retired section whose review judged the underlying objective')
print('worth keeping, and named a live level that does not already teach it.')
print('Nothing here is applied: the rewrite patcher skips a retired section, so')
print('every one of these needs a decision before it reaches a learner.\n')
print(f'{len(rows)} candidates across {len({r[0] for r in rows})} retired sections.\n')
print('| Candidate | From | Proposed destination | Objective |')
print('| --- | --- | --- | --- |')
for category, item_id, dest, objective, _ in rows:
    print(f'| `{item_id}` | {category} | {dest} | {objective} |')
print('\n## Why each one, in the reviewer\'s words\n')
for category, item_id, dest, _, rationale in rows:
    print(f'**`{item_id}` → {dest}.** {rationale}\n')
